// 《战斗属性与技能特性词条总表》(docs/combat-affix-table.md) → 角色词条 (Content/Rules/Affixes).
// Every line of the table is one entry: [table text, affix id, spec, note]. scripts/gen-affixes.mjs writes
// the affix files; character.mjs registers the stats/triggers; combat-runtime.mjs and character.mjs read them.
//   S(stat, n)            summed stat, value = param n
//   M(stat, n)            independent multiplier ("额外提高"), value = param n (percent)
//   F(stat)               flag (switch), value 1
//   R(stat, per, n)       ratio "每 per 点 … +n", value = n / per
//   T(trigger, params, stitched)   stateful mechanic reading its own params; stitched 'cast' = mounted skill
//   X(id)                 an existing affix file (name is set to the table text)
// Elements (params element/source): 0 火焰 1 冰霜 2 闪电 3 物理 4 毒素 5 虚空; source -1 = any hit, -2 = elemental hits.

const S = (stat, n) => ({ sheet: [{ stat, value: { param: 'n' } }], params: { n }, stats: [[stat, 'sum']] });
const M = (stat, n) => ({ sheet: [{ stat, value: { param: 'n' } }], params: { n }, stats: [[stat, 'more']] });
const F = stat => ({ sheet: [{ stat, value: 1 }], params: {}, stats: [[stat, 'max']] });
const R = (stat, per, n) => ({ sheet: [{ stat, value: { div: [{ param: 'n' }, { param: 'per' }] } }], params: { per, n }, stats: [[stat, 'sum']] });
const T = (trigger, params, stitched = '') => ({ sheet: [{ trigger }], params, trigger: { name: trigger, params: Object.keys(params), stitched } });
const X = id => ({ existing: id });

const FIRE = 0, FROST = 1, LIGHTNING = 2, PHYSICAL = 3, VOID = 5;
const extra = (element, source = -1, n = 15) => T('extra_damage', { n, source, element });
const convert = (element, source = PHYSICAL, n = 30) => T('convert_damage', { n, source, element });

