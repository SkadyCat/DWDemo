// Data-only catalog export; runtime behavior is implemented in DWRulesCore, never evaluated as JS in UE.
import fs from 'node:fs';
import path from 'node:path';
import { SHEET_STATS, SHEET_TRIGGERS } from '../engine/character.mjs';
import { PROJECT_ROOT } from './rule-files.mjs';

const q = text => `TEXT(${JSON.stringify(text)})`;
const lines = ['// Generated by CustomTools/RuleStudio/scripts/export-native-contract.mjs. Do not edit.', '// Attribute combination and trigger parameter contracts; no runtime behavior.'];
for (const [name, combine] of SHEET_STATS) lines.push(`Stats.Add(${q(name)}, ESheetCombine::${{ sum: 'Sum', more: 'More', max: 'Max' }[combine]});`);
for (const [name, spec] of Object.entries(SHEET_TRIGGERS)) lines.push(`Triggers.Add(${q(name)}, FDWSheetTriggerSpec{ { ${spec.params.map(q).join(', ')} }, EStitchRole::${{ cast: 'Cast', grant: 'Grant' }[spec.stitched] || 'None'} });`);
const text = lines.join('\n') + '\n';
const file = path.join(PROJECT_ROOT, 'Plugins/DWRules/Source/DWRulesCore/Private/Generated/DWRuleSheetCatalog.inl');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== text) { console.error('Native sheet catalog is stale. Run node scripts/export-native-contract.mjs.'); process.exitCode = 1; }
} else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); }
console.log(`${SHEET_STATS.size} sheet stats, ${Object.keys(SHEET_TRIGGERS).length} trigger contracts`);
